#!/usr/bin/env bash
# Regenerates TRANSCRIPT.md: every client compiled against every compiler (source compat), and the classes compiled
# against one compiler run against each of the others (binary compat). Needs `coursier` and the compilers below.
#
#   18  released 2.13.18
#   pr  scala/scala#11306 (trait Analyzer self-typed AbstractAnalyzer), published locally as 2.13.99
#   alt the comment-variant (abstract class Analyzer), published locally as 2.13.98
set -u
cd "$(dirname "$0")"
declare -A VER=( [18]=2.13.18 [pr]=2.13.99 [alt]=2.13.98 )
ORDER=(18 pr alt)
OUT=TRANSCRIPT.md
WORK=${TMPDIR:-/tmp}/analyzer-compat-demo; rm -rf "$WORK"; mkdir -p "$WORK"

cp_of() { # jars for a compiler label
  local v=${VER[$1]}; local f=$WORK/cp-$1.txt
  [ -s "$f" ] || coursier fetch -r ivy2Local -r central --classpath \
    org.scala-lang:scala-compiler:$v org.scala-lang:scala-reflect:$v org.scala-lang:scala-library:$v \
    --force-version org.scala-lang:scala-library:$v --force-version org.scala-lang:scala-reflect:$v \
    --force-version org.scala-lang:scala-compiler:$v > "$f" 2>/dev/null
  cat "$f"
}
srcs() { # sources of a client for compiler label $2
  local c=$1 l=$2
  if [ -d clients/$c/shared ]; then
    local variant=old; [ "$l" = pr ] && variant=new
    echo clients/$c/shared/*.scala clients/$c/$variant/*.scala common/*.scala
  else echo clients/$c/*.scala common/*.scala; fi
}
first() { grep -m1 -E '^(ok|FAIL|Exception|java\.|Error)' | sed -e 's/^Exception in thread "main" //' -e 's/ (Client.*//' | cut -c1-170; }

CLIENTS=$(ls clients)
{
echo "# Transcript"; echo
echo "Generated by \`run.sh\` on $(date -u +%F). Compilers: ${ORDER[*]/#/} = $(for l in "${ORDER[@]}"; do printf '%s=%s ' $l ${VER[$l]}; done)"; echo
echo "## Source compat: compile each client with each compiler"; echo
echo "| client | 18 | pr | alt |"; echo "|---|---|---|---|"
for c in $CLIENTS; do
  row="| $c |"
  for l in "${ORDER[@]}"; do
    d=$WORK/classes-$c-$l; mkdir -p $d
    if msg=$(java -cp "$(cp_of $l)" scala.tools.nsc.Main -usejavacp:false -nowarn -classpath "$(cp_of $l)" -d $d $(srcs $c $l) 2>&1); then row+=" ok |"
    else echo "$c on $l: $msg" > $WORK/srcfail-$c-$l.txt; rm -rf $d; row+=" **compile error** |"; fi
  done
  echo "$row"
done
echo; echo "## Binary compat: compiled on row, run on column"; echo
echo "Each cell is the one-line outcome of \`java -cp <classes>:<column's compiler jars> Main\`."; echo
for c in $CLIENTS; do
  echo "### $c"; echo; echo "| compiled on \\ run on | 18 | pr | alt |"; echo "|---|---|---|---|"
  for cl in "${ORDER[@]}"; do
    [ -d $WORK/classes-$c-$cl ] || continue
    row="| $cl |"
    for rl in "${ORDER[@]}"; do
      src=; [ -f clients/$c/source.txt ] && src=$(cat clients/$c/source.txt); res=$(java ${src:+"-Ddemo.source=$src"} -cp "$WORK/classes-$c-$cl:$(cp_of $rl)" Main 2>&1 | grep -v '^\s*at ' | first)
      row+=" \`${res:-no output}\` |"
    done
    echo "$row"
  done; echo
done
echo "## Compile errors"; echo
for f in $WORK/srcfail-*.txt; do [ -e "$f" ] || continue; echo '```'; cat "$f"; echo '```'; echo; done
} > $OUT
echo wrote $OUT
